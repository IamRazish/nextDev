import type { FillRule, Point } from "./clippath";

/**
 * The shape tables from the standalone editor, with two corrections:
 * `Cross` closed on a stray (0, 20) vertex that left a spike in its outline,
 * and `Frame` is a self-intersecting outline, so it only renders hollow under
 * the even-odd fill rule — nonzero paints it as a solid block.
 */
const shape = (name: string, seeds: [number, number][], fillRule: FillRule = "nonzero") => ({
  name,
  fillRule,
  points: seeds.map(([x, y]): Point => ({ x, y })),
});

